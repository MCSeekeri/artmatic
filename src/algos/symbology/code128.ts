/**
 * code128.ts — 一维条形码：Code 128（subset B），**完整标准编码**。
 *
 * 图案表逐字取自 `lindell/JsBarcode` 的 `CODE128/constants.js`（MIT，见
 * `CREDITS.md` §二）—— 108 个符号的条空宽度是**表数据**，没有公式：
 * 凭记忆写必错，而错一位的后果是「看着像条形码、扫不出来」。
 *
 * 只做 subset B（ASCII 32..127）：A（控制字符）/ C（成对数字压缩）会让同一段
 * 文本有多种合法编码，图案随之变化 —— 那对「图案」这个用途没有价值，却让
 * 参考对拍失去唯一的答案。非 ASCII 字符退化成 `?`（Code 128 本来就不带中文）。
 *
 * 校验位是 mod 103（标准 §4.3.5.2）：`(StartB + Σ value_i × i) mod 103`。
 */

