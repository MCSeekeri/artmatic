const START_B = 104;
const STOP = 106;
const MODULO = 103;

/** 单个符号的图案（位串，长度 11；STOP 是 13）。 */
export function code128SymbolPattern(value: number): string {
  return String(BARS[value]);
}

export interface Code128Result {
  /** 模块序列：1 = 条，0 = 空。**不含**静区。 */
  modules: Uint8Array;
  /** 实际编码的 ASCII 文本（非 ASCII 已退化成 `?`）。 */
  text: string;
  /** 校验位（0..102），工具面 / 测试用。 */
  checksum: number;
}

/** 内容长度上限。超过就截断 —— 再长下去一维码的模块会细到一个像素以下。 */
export const CODE128_MAX_CHARS = 48;

export function encodeCode128(content: string): Code128Result {
  const ascii: number[] = [];
  for (const ch of content) {
    if (ascii.length >= CODE128_MAX_CHARS) break;
    const code = ch.codePointAt(0)!;
    ascii.push(code >= 32 && code <= 127 ? code : 63); // 63 = '?'
  }
  if (ascii.length === 0) ascii.push(32);

  const values = ascii.map((c) => c - 32);
  let sum = START_B;
  for (let i = 0; i < values.length; i++) sum += values[i]! * (i + 1);
  const checksum = sum % MODULO;

  const symbols = [START_B, ...values, checksum, STOP];
  const bits: number[] = [];
  for (const s of symbols) {
    const pattern = code128SymbolPattern(s);
    for (const c of pattern) bits.push(c === '1' ? 1 : 0);
  }

  return {
    modules: Uint8Array.from(bits),
    text: String.fromCharCode(...ascii),
    checksum,
  };
}
